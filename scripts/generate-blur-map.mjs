/**
 * Walks content image roots under `public/` and writes ThumbHash strings to
 * `src/lib/blur-map.generated.ts`. Run via `npm run generate:blur-map`.
 *
 * Skips videos, SVGs, and UI icons. Does not write extra image files.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { rgbaToThumbHash } from "thumbhash";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUT_FILE = path.join(ROOT, "src/lib/blur-map.generated.ts");

/** Content roots relative to `public/` (site paths are `/${rel}`). */
const SCAN_ROOTS = ["avatar", "photos", "work"];

const IMAGE_EXT = new Set([".webp", ".jpg", ".jpeg", ".png", ".gif", ".avif"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
      continue;
    }
    if (!entry.isFile()) continue;
    const ext = path.extname(entry.name).toLowerCase();
    if (!IMAGE_EXT.has(ext)) continue;
    files.push(full);
  }
  return files;
}

async function hashFile(filePath) {
  // ThumbHash wants RGBA ≤100px on the long edge.
  const { data, info } = await sharp(filePath)
    .rotate()
    .resize(100, 100, { fit: "inside" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const hash = rgbaToThumbHash(info.width, info.height, data);
  return Buffer.from(hash).toString("base64");
}

async function main() {
  const map = {};
  const files = [];

  for (const root of SCAN_ROOTS) {
    const dir = path.join(PUBLIC_DIR, root);
    try {
      files.push(...(await walk(dir)));
    } catch (error) {
      if (error && error.code === "ENOENT") continue;
      throw error;
    }
  }

  files.sort();

  for (const filePath of files) {
    const rel = path.relative(PUBLIC_DIR, filePath).split(path.sep).join("/");
    const sitePath = `/${rel}`;
    try {
      map[sitePath] = await hashFile(filePath);
      process.stdout.write(`✓ ${sitePath}\n`);
    } catch (error) {
      process.stderr.write(
        `✗ ${sitePath}: ${error instanceof Error ? error.message : error}\n`,
      );
    }
  }

  const keys = Object.keys(map).sort();
  const body = keys
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(map[key])},`)
    .join("\n");

  const source = `/* eslint-disable */
/**
 * AUTO-GENERATED by \`scripts/generate-blur-map.mjs\`.
 * Do not edit by hand — run \`npm run generate:blur-map\`.
 */
export const BLUR_THUMBHASH_BY_PATH: Record<string, string> = {
${body}
};
`;

  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, source, "utf8");
  process.stdout.write(
    `\nWrote ${keys.length} hashes → ${path.relative(ROOT, OUT_FILE)}\n`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
